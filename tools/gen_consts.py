"""Generate src/oa_consts.h: OpenACELP's own fixed-point constant tables.

Everything here is computed from formulas (no ETSI data):
  - adaptive-codebook interpolation taps (Hamming-windowed sinc, +-16 samples)
  - powers of the bandwidth-expansion factors gamma
  - log2 / pow2 interpolation tables
  - encoder analysis window, lag window and LSP search grid
"""
import math
import sys

out = []
w = out.append


def arr(name, ctype, values, per_line=8):
    w(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        w("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    w("};")
    w("")


def q(x, bits):
    return int(round(x * (1 << bits)))


w("/* Generated by tools/gen_consts.py. Do not edit. */")
w("#ifndef OA_CONSTS_H")
w("#define OA_CONSTS_H")
w("#include <stdint.h>")
w("")

# Interpolation taps for fractions 1/3 and 2/3. Tap k (k = -15..16) multiplies
# x(x0 + k) where the wanted point is x0 + mu.
HALF = 16
taps = []
for mu in (1 / 3, 2 / 3):
    row = []
    for k in range(-HALF + 1, HALF + 1):
        t = k - mu
        s = math.sin(math.pi * t) / (math.pi * t)
        win = 0.54 + 0.46 * math.cos(math.pi * t / HALF)
        row.append(min(32767, q(s * win, 15)))
    taps += row
w(f"#define OA_INTERP_TAPS {2 * HALF}")
w(f"#define OA_INTERP_K0   {-HALF + 1}")
arr("oa_interp_q15", "int16_t", taps)

# Correlation interpolation for the encoder's fractional search (+-4 samples, 8 taps)
HALF_C = 4
ctaps = []
for mu in (0.0, 1 / 3, 2 / 3):
    for k in range(-HALF_C + 1, HALF_C + 1):
        t = k - mu
        s = 1.0 if abs(t) < 1e-12 else math.sin(math.pi * t) / (math.pi * t)
        win = 0.54 + 0.46 * math.cos(math.pi * t / HALF_C)
        ctaps.append(min(32767, q(s * win, 15)))
w(f"#define OA_CINTERP_TAPS {2 * HALF_C}")
w(f"#define OA_CINTERP_K0   {-HALF_C + 1}")
arr("oa_cinterp_q15", "int16_t", ctaps)

# gamma powers, Q15, index 0..10
for name, g in (("g075", 0.75), ("g085", 0.85), ("g095", 0.95), ("g060", 0.60)):
    arr(f"oa_{name}_q15", "int16_t", [min(32767, q(g ** i, 15)) for i in range(11)])

# log2(1 + i/64), i = 0..64, Q16 (interpolated)
arr("oa_log2_tab", "uint32_t", [q(math.log2(1 + i / 64), 16) for i in range(65)])
# 2^(i/64), i = 0..64, Q30
arr("oa_pow2_tab", "uint32_t", [q(2 ** (i / 64), 30) for i in range(65)])

# --- encoder constants ---
L1, L2 = 216, 40
win = [0.54 - 0.46 * math.cos(math.pi * n / (L1 - 1)) for n in range(L1)]
win += [0.54 + 0.46 * math.cos(math.pi * (n - L1) / (L2 - 1)) for n in range(L1, L1 + L2)]
arr("oa_lpc_window_q15", "int16_t", [min(32767, q(x, 15)) for x in win])
lag = [1.0] + [math.exp(-0.5 * (2 * math.pi * 60 * i / 8000) ** 2) / 1.00005 for i in range(1, 11)]
arr("oa_lag_window_q30", "int32_t", [q(x, 30) for x in lag])
GRID = 120   # encoder-only; the spec uses 60, a finer grid separates close roots
arr("oa_lsp_grid_q15", "int16_t", [max(-32767, min(32767, q(math.cos(math.pi * i / GRID), 15))) for i in range(GRID + 1)])
w(f"#define OA_GRID_POINTS {GRID + 1}")
w("")
w("#endif")

path = sys.argv[1] if len(sys.argv) > 1 else "src/oa_consts.h"
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path)
