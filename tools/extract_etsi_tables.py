"""
Regenerate src/oa_tables_tetra.c, OpenACELP's TETRA codebooks, from a copy
of ETSI EN 300 395-2 (the C-CODE directory of the ETSI ZIP).

Only the numeric values are taken. They are written into OpenACELP's own
arrays, with its own names and comments: no ETSI code, text or table layout
is reproduced. This is a maintainer tool, to regenerate or verify the
committed file; building OpenACELP does not need it.

Usage:
    extract_etsi_tables.py <path/to/c-code> <out.c>

Values read:
    clsp_334.tab : LSP split-VQ codebooks, cosine domain, Q15
                   256x3, 512x3, 512x4
    ener_qua.tab : pitch and code energy codebook, Q8, 64x2
"""
import re
import sys
from pathlib import Path

# (file, array to read, OpenACELP array, rows, cols, Q format)
TABLES = [
    ("clsp_334.tab", "dico1_clsp", "oa_tetra_lsp_cb1", 256, 3, 15),
    ("clsp_334.tab", "dico2_clsp", "oa_tetra_lsp_cb2", 512, 3, 15),
    ("clsp_334.tab", "dico3_clsp", "oa_tetra_lsp_cb3", 512, 4, 15),
    ("ener_qua.tab", "t_qua_ener", "oa_tetra_gain_cb", 64, 2, 8),
]

TERM = re.compile(r"^\s*(-?\d+)\s*(?:\*\s*(\d+))?\s*$")   # "N" or "N * M"


def find_file(src: Path, name: str) -> Path:
    # ETSI ships upper-case names; accept either case
    for p in src.iterdir():
        if p.name.lower() == name:
            return p
    sys.exit(f"error: {name} not found in {src}")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def parse_array(text: str, name: str) -> list[int]:
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
    if not m:
        sys.exit(f"error: array {name} not found")
    values = []
    for term in m.group(1).split(","):
        if not term.strip():
            continue
        t = TERM.match(term)
        if not t:   # refuse anything that is not a plain integer (times a constant)
            sys.exit(f"error: unexpected element '{term.strip()}' in {name}")
        v = int(t.group(1)) * (int(t.group(2)) if t.group(2) else 1)
        if not -32768 <= v <= 32767:
            sys.exit(f"error: value {v} in {name} does not fit int16")
        values.append(v)
    return values


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = Path(sys.argv[1]), Path(sys.argv[2])

    texts = {}
    c = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
         "",
         "/*",
         " * OpenACELP codebooks for TETRA interoperability (EN 300 395-2).",
         " *",
         " * The values are those of the standard, so that OpenACELP decodes and",
         " * encodes TETRA speech; the arrays, names and comments are OpenACELP's own.",
         " * Generated by tools/extract_etsi_tables.py, do not edit.",
         " *",
         " * Each line holds one codevector, followed by its index.",
         " */",
         "",
         '#include "openacelp.h"',
         ""]
    notes = {
        "oa_tetra_lsp_cb1": "LSP split VQ, LSPs 1 to 3, cosine domain, Q15",
        "oa_tetra_lsp_cb2": "LSP split VQ, LSPs 4 to 6, cosine domain, Q15",
        "oa_tetra_lsp_cb3": "LSP split VQ, LSPs 7 to 10, cosine domain, Q15",
        "oa_tetra_gain_cb": "Energies: pitch (R_pitch) then code (R_code), log2, Q8",
    }

    for fname, src_name, c_name, rows, cols, q in TABLES:
        if fname not in texts:
            texts[fname] = strip_comments(find_file(src, fname).read_text(errors="replace"))
        vals = parse_array(texts[fname], src_name)
        if len(vals) != rows * cols:
            sys.exit(f"error: {src_name} has {len(vals)} values, expected {rows * cols}")

        c.append(f"/* {notes[c_name]}: {rows} codevectors of {cols} */")
        c.append(f"static const int16_t {c_name}[{rows} * {cols}] = {{")
        for r in range(rows):
            row = vals[r * cols:(r + 1) * cols]
            c.append("    " + " ".join(f"{v:6d}," for v in row) + f" /* {r:3d} */")
        c += ["};", ""]
        print(f"  {c_name:17s} {rows}x{cols} Q{q}")

    c += ["const oa_tables_t oa_tables_tetra = {",
          "    oa_tetra_lsp_cb1, oa_tetra_lsp_cb2, oa_tetra_lsp_cb3, oa_tetra_gain_cb",
          "};", ""]
    out.write_text("\n".join(c))
    print(f"  wrote {out}")


if __name__ == "__main__":
    main()
