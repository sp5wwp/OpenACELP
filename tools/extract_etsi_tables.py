"""
Extract the TETRA speech codec tables from a user-supplied copy of
ETSI EN 300 395-2 (the C-CODE directory of the ETSI ZIP) and emit them
as a C source/header pair for OpenACELP's table provider.

Nothing from ETSI is stored in this repository: the output goes to the
build directory and must never be committed or redistributed.

Usage:
    extract_etsi_tables.py <path/to/c-code> <out_dir>

Extracted tables (decoder needs only these two files):
    clsp_334.tab : LSP split-VQ codebooks, cosine domain, Q15
                   dico1_clsp 256x3, dico2_clsp 512x3, dico3_clsp 512x4
    ener_qua.tab : energy/gain codebook, Q8, t_qua_ener 64x2
"""
import re
import sys
from pathlib import Path

# (file, array name in ETSI source, our C name, rows, cols, Q format)
TABLES = [
    ("clsp_334.tab", "dico1_clsp", "oa_tetra_lsp_cb1", 256, 3, 15),
    ("clsp_334.tab", "dico2_clsp", "oa_tetra_lsp_cb2", 512, 3, 15),
    ("clsp_334.tab", "dico3_clsp", "oa_tetra_lsp_cb3", 512, 4, 15),
    ("ener_qua.tab", "t_qua_ener", "oa_tetra_gain_cb", 64, 2, 8),
]

TERM = re.compile(r"^\s*(-?\d+)\s*(?:\*\s*(\d+))?\s*$")   # "N" or "N * M"


def find_file(src: Path, name: str) -> Path:
    # ETSI ships upper-case names; accept either case
    for p in src.iterdir():
        if p.name.lower() == name:
            return p
    sys.exit(f"error: {name} not found in {src}")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def parse_array(text: str, name: str) -> list[int]:
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
    if not m:
        sys.exit(f"error: array {name} not found")
    values = []
    for term in m.group(1).split(","):
        if not term.strip():
            continue
        t = TERM.match(term)
        if not t:   # refuse anything that is not a plain integer (times a constant)
            sys.exit(f"error: unexpected element '{term.strip()}' in {name}")
        v = int(t.group(1)) * (int(t.group(2)) if t.group(2) else 1)
        if not -32768 <= v <= 32767:
            sys.exit(f"error: value {v} in {name} does not fit int16")
        values.append(v)
    return values


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)

    texts = {}
    hdr = ["/* Generated by tools/extract_etsi_tables.py from ETSI EN 300 395-2.",
           " * Contains ETSI material: do not commit or redistribute. */",
           "#ifndef OA_TETRA_TABLES_H", "#define OA_TETRA_TABLES_H", "",
           "#include <stdint.h>", ""]
    src_c = ["/* Generated by tools/extract_etsi_tables.py from ETSI EN 300 395-2.",
             " * Contains ETSI material: do not commit or redistribute. */",
             '#include "tetra_tables.h"', ""]

    for fname, etsi_name, c_name, rows, cols, q in TABLES:
        if fname not in texts:
            texts[fname] = strip_comments(find_file(src, fname).read_text(errors="replace"))
        vals = parse_array(texts[fname], etsi_name)
        if len(vals) != rows * cols:
            sys.exit(f"error: {etsi_name} has {len(vals)} values, expected {rows * cols}")

        up = c_name.upper()
        hdr += [f"#define {up}_ROWS {rows}", f"#define {up}_COLS {cols}",
                f"#define {up}_Q    {q}",
                f"extern const int16_t {c_name}[{up}_ROWS * {up}_COLS];", ""]
        src_c.append(f"const int16_t {c_name}[{up}_ROWS * {up}_COLS] = {{")
        for r in range(rows):
            row = vals[r * cols:(r + 1) * cols]
            src_c.append("    " + ", ".join(f"{v:6d}" for v in row) + ",")
        src_c += ["};", ""]
        print(f"  {etsi_name:11s} -> {c_name:17s} {rows}x{cols} Q{q}")

    hdr += ['#include "openacelp.h"', "extern const oa_tables_t oa_tables_tetra;", "", "#endif", ""]
    src_c += ["const oa_tables_t oa_tables_tetra = {",
              "    oa_tetra_lsp_cb1, oa_tetra_lsp_cb2, oa_tetra_lsp_cb3, oa_tetra_gain_cb",
              "};", ""]
    (out / "tetra_tables.h").write_text("\n".join(hdr))
    (out / "tetra_tables.c").write_text("\n".join(src_c))
    print(f"  wrote {out}/tetra_tables.[ch]")


if __name__ == "__main__":
    main()
